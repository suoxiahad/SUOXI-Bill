export function toBengaliDigits(value: number | string): string {
  return String(value).replace(/\d/g, (d) => BENGALI_DIGITS[Number(d)] ?? d);
}

export function numberToBengaliWords(num: number): string {
  const n = Math.floor(Math.max(0, Number(num) || 0));
  if (n < 100) {
    return BENGALI_WORDS_0_TO_99[n] || '';
  }
  if (n < 1000) {
    const hundreds = Math.floor(n / 100);
    const rem = n % 100;
    const hundredWord = `${BENGALI_WORDS_0_TO_99[hundreds]}শ`;
    return rem === 0 ? hundredWord : `${hundredWord} ${BENGALI_WORDS_0_TO_99[rem]}`;
  }
  return toBengaliDigits(n);
}

export function formatBengaliDayWithWord(days: number): string {
  const safeDays = Math.max(1, Math.round(Number(days) || 10));
  return `${toBengaliDigits(safeDays)} (${numberToBengaliWords(safeDays)})`;
}
